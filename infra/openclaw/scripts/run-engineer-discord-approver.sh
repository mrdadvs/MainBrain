#!/usr/bin/env bash
set -euo pipefail

ROOT="/home/mdv/mainbrain"
APP_DIR="${ROOT}/apps/engineer_discord_approver"
VENV_DIR="${HOME}/.local/share/mainbrain/engineer-discord-approver-venv"

DISCORD_TOKEN="${DISCORD_RELEASE_APPROVER_BOT_TOKEN:-}"
EXECUTOR_SOCKET_PATH="${ENGINEER_RELEASE_EXECUTOR_SOCKET_PATH:-${ROOT}/data/engineer-release-executor/release-executor.sock}"
EXECUTOR_AUTH_TOKEN="${ENGINEER_RELEASE_EXECUTOR_DISCORD_AUTH_TOKEN:-}"
ALLOWED_USER_IDS="${ENGINEER_RELEASE_APPROVER_ALLOWED_USER_IDS:-1568655444321243136}"
ALLOWED_GUILD_IDS="${ENGINEER_RELEASE_APPROVER_ALLOWED_GUILD_IDS:-1568656073898987651}"
ALLOWED_CHANNEL_IDS="${ENGINEER_RELEASE_APPROVER_ALLOWED_CHANNEL_IDS:-1570598910173646890}"
ANNOUNCE_CHANNEL_ID="${ENGINEER_RELEASE_APPROVER_ANNOUNCE_CHANNEL_ID:-1570598910173646890}"

if [[ -z "${DISCORD_TOKEN}" ]]; then
  echo "DISCORD_RELEASE_APPROVER_BOT_TOKEN must not be empty" >&2
  exit 1
fi
if [[ -z "${EXECUTOR_AUTH_TOKEN}" ]]; then
  echo "ENGINEER_RELEASE_EXECUTOR_DISCORD_AUTH_TOKEN must not be empty" >&2
  exit 1
fi

mkdir -p "$(dirname "${VENV_DIR}")"
if [[ ! -x "${VENV_DIR}/bin/python" ]]; then
  python3 -m venv "${VENV_DIR}"
  "${VENV_DIR}/bin/pip" install --upgrade pip
fi
"${VENV_DIR}/bin/pip" install -r "${APP_DIR}/requirements.txt"

export DISCORD_RELEASE_APPROVER_BOT_TOKEN="${DISCORD_TOKEN}"
export ENGINEER_RELEASE_EXECUTOR_SOCKET_PATH="${EXECUTOR_SOCKET_PATH}"
export ENGINEER_RELEASE_EXECUTOR_DISCORD_AUTH_TOKEN="${EXECUTOR_AUTH_TOKEN}"
export ENGINEER_RELEASE_APPROVER_ALLOWED_USER_IDS="${ALLOWED_USER_IDS}"
export ENGINEER_RELEASE_APPROVER_ALLOWED_GUILD_IDS="${ALLOWED_GUILD_IDS}"
export ENGINEER_RELEASE_APPROVER_ALLOWED_CHANNEL_IDS="${ALLOWED_CHANNEL_IDS}"
export ENGINEER_RELEASE_APPROVER_ANNOUNCE_CHANNEL_ID="${ANNOUNCE_CHANNEL_ID}"

exec "${VENV_DIR}/bin/python" "${APP_DIR}/bot.py"
