#!/usr/bin/env bash
set -euo pipefail

ROOT="/home/mdv/mainbrain"
SOCKET_PATH="${ENGINEER_RELEASE_EXECUTOR_SOCKET_PATH:-${ROOT}/data/engineer-release-executor/release-executor.sock}"
STATE_DIR="${ENGINEER_RELEASE_EXECUTOR_STATE_DIR:-${HOME}/.local/state/mainbrain/engineer-release-executor}"
POLICY_FILE="${ENGINEER_RELEASE_EXECUTOR_POLICY_FILE:-${ROOT}/apps/engineer_release_executor/config/trusted_policy.json}"
WORKSPACES_ROOT="${ENGINEER_RELEASE_EXECUTOR_WORKSPACES_ROOT:-${ROOT}/data/engineer-code-mcp/workspaces}"
WORKSPACE_META_ROOT="${ENGINEER_RELEASE_EXECUTOR_WORKSPACE_META_ROOT:-${WORKSPACES_ROOT}/_engineer_meta}"
ALLOWED_PEER_UID="${ENGINEER_RELEASE_EXECUTOR_ALLOWED_PEER_UID:-1000}"
AUTH_TOKEN="${ENGINEER_RELEASE_EXECUTOR_AUTH_TOKEN:-engineer-release-executor-dev-token}"
EVIDENCE_AUTH_TOKEN="${ENGINEER_RELEASE_EXECUTOR_EVIDENCE_AUTH_TOKEN:-engineer-release-evidence-dev-token}"
DISCORD_AUTH_TOKEN="${ENGINEER_RELEASE_EXECUTOR_DISCORD_AUTH_TOKEN:-}"
DISCORD_ALLOWED_USER_IDS="${ENGINEER_RELEASE_EXECUTOR_DISCORD_ALLOWED_USER_IDS:-1568655444321243136}"
DISCORD_ALLOWED_GUILD_IDS="${ENGINEER_RELEASE_EXECUTOR_DISCORD_ALLOWED_GUILD_IDS:-1568656073898987651}"
DISCORD_ALLOWED_CHANNEL_IDS="${ENGINEER_RELEASE_EXECUTOR_DISCORD_ALLOWED_CHANNEL_IDS:-1570598910173646890}"
DISCORD_INTENT_TTL_MINUTES="${ENGINEER_RELEASE_EXECUTOR_DISCORD_INTENT_TTL_MINUTES:-15}"
DISCORD_APPROVAL_TTL_MINUTES="${ENGINEER_RELEASE_EXECUTOR_DISCORD_APPROVAL_TTL_MINUTES:-60}"

if [[ -z "${AUTH_TOKEN}" ]]; then
  echo "ENGINEER_RELEASE_EXECUTOR_AUTH_TOKEN must not be empty" >&2
  exit 1
fi
if [[ -z "${EVIDENCE_AUTH_TOKEN}" ]]; then
  echo "ENGINEER_RELEASE_EXECUTOR_EVIDENCE_AUTH_TOKEN must not be empty" >&2
  exit 1
fi
if [[ -z "${DISCORD_AUTH_TOKEN}" ]]; then
  echo "ENGINEER_RELEASE_EXECUTOR_DISCORD_AUTH_TOKEN must not be empty" >&2
  exit 1
fi

mkdir -p "$(dirname "${SOCKET_PATH}")"
mkdir -p "${STATE_DIR}"
chmod 700 "${STATE_DIR}"
export ENGINEER_RELEASE_EXECUTOR_AUTH_TOKEN="${AUTH_TOKEN}"
export ENGINEER_RELEASE_EXECUTOR_EVIDENCE_AUTH_TOKEN="${EVIDENCE_AUTH_TOKEN}"
export ENGINEER_RELEASE_EXECUTOR_DISCORD_AUTH_TOKEN="${DISCORD_AUTH_TOKEN}"
export ENGINEER_RELEASE_EXECUTOR_DISCORD_ALLOWED_USER_IDS="${DISCORD_ALLOWED_USER_IDS}"
export ENGINEER_RELEASE_EXECUTOR_DISCORD_ALLOWED_GUILD_IDS="${DISCORD_ALLOWED_GUILD_IDS}"
export ENGINEER_RELEASE_EXECUTOR_DISCORD_ALLOWED_CHANNEL_IDS="${DISCORD_ALLOWED_CHANNEL_IDS}"
export ENGINEER_RELEASE_EXECUTOR_DISCORD_INTENT_TTL_MINUTES="${DISCORD_INTENT_TTL_MINUTES}"
export ENGINEER_RELEASE_EXECUTOR_DISCORD_APPROVAL_TTL_MINUTES="${DISCORD_APPROVAL_TTL_MINUTES}"
export ENGINEER_RELEASE_EXECUTOR_STATE_DIR="${STATE_DIR}"
export ENGINEER_RELEASE_EXECUTOR_POLICY_FILE="${POLICY_FILE}"
export ENGINEER_RELEASE_EXECUTOR_WORKSPACES_ROOT="${WORKSPACES_ROOT}"
export ENGINEER_RELEASE_EXECUTOR_WORKSPACE_META_ROOT="${WORKSPACE_META_ROOT}"

exec python3 "${ROOT}/apps/engineer_release_executor/server.py" serve \
  --socket-path "${SOCKET_PATH}" \
  --allowed-peer-uid "${ALLOWED_PEER_UID}"
